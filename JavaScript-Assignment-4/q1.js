// 1. Arithmetic Operators
let num1 = 10;
let num2 = 3;
console.log("--- Answer 1 ---");
console.log("--- Arithmetic Operators ---");
console.log("num1 = 10, num2 = 3");
console.log("10 + 3 =", num1 + num2);
console.log("10 - 3 =", num1 - num2);
console.log("10 * 3 =", num1 * num2);
console.log("10 / 3 =", num1 / num2);
console.log("10 % 3 =", num1 % num2);

let count = 5;
console.log("Initial count:", count);
count++; // Increment
console.log("After Increment (++):", count);
count--; // Decrement
console.log("After Decrement (--):", count);

// 2. Assignment Operators
console.log("--- Assignment Operators ---");
let x = 20; // =
console.log("Initial x:", x);

x += 5; // x = x + 5
console.log("x += 5:", x);

x -= 3; // x = x - 3
console.log("x -= 3:", x);

x *= 2; // x = x * 2
console.log("x *= 2:", x);

x /= 4; // x = x / 4
console.log("x /= 4:", x);

// 3. Comparison Operators
console.log("--- Comparison Operators ---");
let a = 10;
let b = "10";
let c = 15;

console.log("a == b:", a == b);
console.log("a === b:", a === b);
console.log("a != c:", a != c);
console.log("a !== b:", a !== b);
console.log("c > a:", c > a);
console.log("a < c:", a < c);
console.log("a >= 10:", a >= 10);
console.log("c <= 10:", c <= 10);